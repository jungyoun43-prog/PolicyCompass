const binaryAssets = [
  {
    route: "/assets/visit-prep-hero.png",
    file: "src/assets/visit-prep-hero.png",
    type: "image/png",
  },
  {
    route: "/assets/body-atlas-v4.webp",
    file: "src/assets/body-atlas-v4.webp",
    type: "image/webp",
  },
];

const sourceEntries = await Promise.all(
  sourceAssets.map(async ({ route, file, type }) => [
    route,
    { body: await readFile(file, "utf8"), type },
  ]),
);

const binaryEntries = await Promise.all(
  binaryAssets.map(async ({ route, file, type }) => [
    route,
    { body: (await readFile(file)).toString("base64"), encoding: "base64", type },
  ]),
);

const assets = Object.fromEntries([...sourceEntries, ...binaryEntries]);
const workerSource = `// Generated by scripts/build.mjs. Source lives in src/.
const assets = ${JSON.stringify(assets)};
const baseHeaders = {
  "cache-control": "no-store",
  "content-security-policy": "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; font-src 'self'; connect-src 'none'; object-src 'none'; frame-ancestors 'none'; base-uri 'self'; form-action 'self'",
  "permissions-policy": "camera=(), microphone=(), geolocation=()",
  "referrer-policy": "no-referrer",
  "x-content-type-options": "nosniff",
  "x-frame-options": "DENY"
};

function decodeBase64(value) {
  const decoded = atob(value);
  return Uint8Array.from(decoded, (character) => character.charCodeAt(0));
}

export default {
  async fetch(request) {
    if (request.method !== "GET" && request.method !== "HEAD") {
      return new Response("Method not allowed", {
        status: 405,
        headers: { ...baseHeaders, allow: "GET, HEAD" }
      });
    }

    const url = new URL(request.url);
    const route = url.pathname === "/index.html" ? "/" : url.pathname;
    const asset = assets[route];
    if (!asset) {
      return new Response("Not found", { status: 404, headers: baseHeaders });
    }

    const body = request.method === "HEAD"
      ? null
      : asset.encoding === "base64"
        ? decodeBase64(asset.body)
        : asset.body;

    return new Response(body, {
      headers: { ...baseHeaders, "content-type": asset.type }
    });
  }
};
`;

await rm("dist", { recursive: true, force: true });
await mkdir("dist/server", { recursive: true });
await writeFile("dist/server/index.js", workerSource, "utf8");
